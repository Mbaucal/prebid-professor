/** Writes .generated/browser-canonical-source.mjs: the source text of every
 * function listed in worker/runtime-canonical/functions.mjs, sliced from its
 * repository file. Each slice must equal unbundled Node Function#toString of
 * the imported function, so generated code stays byte-identical to a direct
 * (unbundled) compile even after the Worker bundler renames identifiers.
 * Reads repository files only; no network, database or deployment.
 */
import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {resolve, dirname} from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import {parse} from 'acorn';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const nativeText = Function.prototype.toString;

export async function canonicalSources(root = ROOT) {
  const {runtimeFunctions, testWorkspaceFunctions} = await import(pathToFileURL(resolve(root, 'worker/runtime-canonical/functions.mjs')).href);
  const listed = Object.entries(runtimeFunctions).concat(Object.entries(testWorkspaceFunctions));
  const sources = {};
  for (const [path, names] of listed) {
    assert(!Object.hasOwn(sources, path), `${path} is listed in more than one canonical group.`);
    assert(names.length && new Set(names).size === names.length, `${path} must list each function once.`);
    const text = await readFile(resolve(root, path), 'utf8');
    const declared = new Map();
    for (const node of parse(text, {ecmaVersion: 'latest', sourceType: 'module'}).body) {
      const fn = node.type === 'ExportNamedDeclaration' ? node.declaration : null;
      if (fn?.type === 'FunctionDeclaration') declared.set(fn.id.name, text.slice(fn.start, fn.end));
    }
    const namespace = await import(pathToFileURL(resolve(root, path)).href);
    sources[path] = {};
    for (const name of names) {
      assert(declared.has(name), `${path}: ${name} must be an exported function declaration.`);
      assert.equal(typeof namespace[name], 'function', `${path}: ${name} is not an exported function.`);
      // The prototype method, not namespace[name].toString(): an installer may
      // already have run in this process.
      assert.equal(nativeText.call(namespace[name]), declared.get(name),
        `${path}: the source slice of ${name} differs from unbundled Function#toString.`);
      sources[path][name] = declared.get(name);
    }
  }
  return sources;
}

export async function prepareBrowserCanonical(root = ROOT) {
  const sources = await canonicalSources(root);
  await mkdir(resolve(root, '.generated'), {recursive: true});
  await writeFile(resolve(root, '.generated/browser-canonical-source.mjs'),
    '// Generated by scripts/prepare-browser-canonical.mjs from repository sources; equals unbundled Function#toString.\n' +
    `export const canonicalSources=${JSON.stringify(sources)};\n`);
  return Object.fromEntries(Object.entries(sources).map(([path, texts]) => [path, Object.keys(texts)]));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await prepareBrowserCanonical(), null, 2));
}

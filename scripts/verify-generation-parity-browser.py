"""Run every program from scripts/verify-dist-generation-parity.mjs in Chromium.

Each ads.js and ads.min.js was generated by the compiled production Worker (and is
byte-identical to the direct compile). GPT and Prebid are the repository mock
(tests/runtime/mock-ad-libraries.js), a TCF stub reports a completed choice with
every purpose granted, the fixture page is served by a route and every other
request is aborted. One browser and one page; each program gets its own origin, so
no storage (TakeOver interval) carries over. The page clock is virtual.

Required for every program: no uncaught error, a GPT slot for every ad container of
the package's implementation.html, an initial ad request for every container that
is not lazy, pbjs.requestBids when Prebid is enabled, and the TakeOver slot requested
on the first view exactly when the configuration has one. Lazy requests depend on
IntersectionObserver rendering, not on the virtual clock, so they are only recorded.
An error a program throws (also inside a virtual-clock timer) fails that program
only; every program runs and browser-results.json is always written.

The country script the Worker serves (/geo/v1/client.js, byte-identical to the
unbundled route) runs too: its country request gets a synthetic RS answer, and
__AD_GEO.ready() must resolve to it with no uncaught error.
"""
import hashlib
import json
import os
import re
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from playwright.sync_api import sync_playwright

root = Path(__file__).resolve().parent.parent
output = Path(sys.argv[1] if len(sys.argv) > 1 else root / '.generated/generation-parity')
manifest = json.loads((output / 'manifest.json').read_text())
mock = (root / 'tests/runtime/mock-ad-libraries.js').read_text()
now = datetime(2026, 11, 14, 12, tzinfo=timezone.utc)
TAKEOVER_SLOT = 'adsx-takeover-slot'
GRANT = r'''
() => {
 window.__defined = []; window.__enable = 0;
 const purposes = {}; for (let i = 1; i <= 11; i++) purposes[i] = true;
 const data = {gdprApplies: true, cmpStatus: 'loaded', eventStatus: 'useractioncomplete', tcString: 'synthetic-granted', listenerId: 1,
  purpose: {consents: purposes, legitimateInterests: purposes}, vendor: {consents: {}, legitimateInterests: {}}};
 window.__tcfapi = (command, version, callback) => {
  if (command === 'addEventListener' || command === 'getTCData') setTimeout(() => callback(data, true), 0);
  else if (command === 'ping') callback({gdprApplies: true, cmpLoaded: true, cmpStatus: 'loaded'}, true);
  else callback(true, true);
 };
 const define = googletag.defineSlot;
 googletag.defineSlot = function(path, sizes, id) { __defined.push(id); return define.apply(this, arguments); };
 const enable = googletag.enableServices;
 googletag.enableServices = function() { __enable++; return enable.apply(this, arguments); };
}
'''
STATE = '''() => ({defined: window.__defined, enableServices: window.__enable,
 requests: __testAds.observations.requests.map(request => request.id), bids: __testAds.observations.bids.length,
 accounts: window.__AD_BIDDER_ACCOUNTS?.snapshot().accounts ?? []})'''
ACCOUNT_MOCK = '''() => {
 pbjs.version='11.34.0'; pbjs.aliasRegistry={};
 pbjs.aliasBidder=(base,alias)=>{pbjs.aliasRegistry[alias]=base;};
 pbjs.setBidderConfig=config=>{__testAds.observations.configs.push(config);};
}'''
EMPTY = {'defined': [], 'enableServices': 0, 'requests': [], 'bids': 0}
COUNTRY = json.dumps({'version': 1, 'status': 'known', 'country': 'RS', 'source': 'cloudflare'})


def containers(html):
    body = re.search(r'<body>([\s\S]*?)</body>', html).group(1)
    body = re.sub(r'<script[\s\S]*?</script>', '', body)
    found = re.findall(r'<div id="([^"]+)" class="([^"]*\bwrapperAd\b[^"]*)"', body)
    assert found, 'implementation.html has no ad container'
    return body, [(name, 'lazyAd' in classes.split()) for name, classes in found]


def check(entry, errors, initial, final, slots):
    problems = []
    if errors:
        problems.append('uncaught: ' + ' | '.join(sorted(set(errors))))
    missing = [slot for slot, _ in slots if slot not in final['defined']]
    if missing:
        problems.append('no GPT slot for ' + ','.join(missing))
    eager = [slot for slot, lazy in slots if not lazy and slot not in initial['requests']]
    if eager or not initial['requests']:
        problems.append('no initial ad request for ' + (','.join(eager) or 'any slot'))
    if entry['demand'] == 'prebid' and not final['bids']:
        problems.append('no pbjs.requestBids')
    if entry.get('accountCase'):
        accounts={row['bidder']:row for row in final.get('accounts',[])}
        for code,mode in [('adf_smn','inherit'),('adf_ag','none'),('adf_other','custom'),('pubmatic','inherit')]:
            if accounts.get(code,{}).get('mode')!=mode or accounts.get(code,{}).get('status')!='configured':
                problems.append('account did not configure: '+code)
    if entry['takeover'] != 'none' and TAKEOVER_SLOT not in initial['requests']:
        problems.append('TakeOver not requested on the first view')
    if entry['takeover'] == 'none' and TAKEOVER_SLOT in final['requests']:
        problems.append('TakeOver requested without a TakeOver configuration')
    return problems


results, failures = [], []
started = time.time()
with sync_playwright() as pw:
    browser = pw.chromium.launch(headless=True, executable_path=os.environ.get('CHROMIUM_PATH'), args=['--no-sandbox'])
    page = browser.new_page(viewport={'width': 1440, 'height': 900})
    fixtures, answers, outbound = {}, {}, []

    def route(request):
        url = request.request.url
        if url in fixtures:
            request.fulfill(content_type='text/html', body='<!doctype html><html><head></head><body>' + fixtures[url] + '<main style="height:2400px"></main></body></html>')
        elif url in answers:
            request.fulfill(content_type='application/json; charset=utf-8', headers={'access-control-allow-origin': '*'}, body=answers[url])
        else:
            outbound.append(url)
            request.abort()
    page.route('**/*', route)
    page.clock.install(time=now)
    counter = 0
    for entry in manifest['entries']:
        directory = output / entry['dir']
        for name, digest in entry['files'].items():
            assert hashlib.sha256((directory / name).read_bytes()).hexdigest() == digest, 'Generated file changed: %s/%s' % (entry['dir'], name)
        body, slots = containers((directory / 'implementation.html').read_text())
        row = {'dir': entry['dir'], 'identicalToDirect': entry['identical'], 'containers': [slot for slot, _ in slots], 'programs': {}}
        for name in ['ads.js', 'ads.min.js']:
            counter += 1
            origin = 'https://p%d.generation-parity.invalid/' % counter
            fixtures[origin] = body
            errors = []
            listener = lambda error, errors=errors: errors.append(str(error).split('\n')[0])

            def attempt(label, action, fallback=None):
                # An error thrown by the program (also inside a virtual-clock timer)
                # fails this program only; every program still runs and is reported.
                try:
                    return action()
                except Exception as error:
                    errors.append('%s: %s' % (label, str(error).split('\n')[0]))
                    return fallback

            def advance(steps):
                for _ in range(steps):
                    attempt('timer', lambda: page.clock.run_for(500))
            page.on('pageerror', listener)
            try:
                page.goto(origin)
                page.add_script_tag(content=mock)
                page.evaluate(GRANT)
                if entry.get('accountCase'): page.evaluate(ACCOUNT_MOCK)
                attempt('script', lambda: page.add_script_tag(content=(directory / name).read_text()))
                advance(6)
                initial = attempt('state', lambda: page.evaluate(STATE), EMPTY)
                attempt('scroll', lambda: page.evaluate('window.scrollTo(0, document.body.scrollHeight)'))
                advance(12)
                final = attempt('state', lambda: page.evaluate(STATE), EMPTY)
            finally:
                page.remove_listener('pageerror', listener)
            problems = check(entry, errors, initial, final, slots)
            row['programs'][name] = {'passed': not problems, 'problems': problems, 'defined': final['defined'],
                                     'initialRequests': initial['requests'], 'requests': final['requests'], 'bids': final['bids']}
            if problems:
                failures.append('%s/%s: %s' % (entry['dir'], name, '; '.join(problems)))
        results.append(row)
        status = 'ok    ' if all(p['passed'] for p in row['programs'].values()) else 'FAILED'
        print(status, entry['dir'], ' | '.join('%s %s' % (n, '; '.join(p['problems']) or 'slots %d requests %d' % (len(p['defined']), len(p['requests']))) for n, p in row['programs'].items()))
    for entry in manifest['served']:
        # The served country script: one request, answered with a synthetic country.
        assert hashlib.sha256((output / entry['file']).read_bytes()).hexdigest() == entry['servedSha256'], 'Served file changed: ' + entry['file']
        counter += 1
        origin = 'https://p%d.generation-parity.invalid/' % counter
        fixtures[origin] = ''
        answers[entry['endpoint']] = COUNTRY
        errors, problems = [], []
        listener = lambda error, errors=errors: errors.append(str(error).split('\n')[0])
        page.on('pageerror', listener)
        try:
            page.goto(origin)
            page.add_script_tag(content=(output / entry['file']).read_text())
            signal = page.evaluate('() => window.__AD_GEO.ready().then(snapshot => ({status: snapshot.status, country: snapshot.country}))')
        except Exception as error:
            signal = None
            errors.append(str(error).split('\n')[0])
        finally:
            page.remove_listener('pageerror', listener)
        if errors:
            problems.append('uncaught: ' + ' | '.join(sorted(set(errors))))
        if signal != {'status': 'known', 'country': 'RS'}:
            problems.append('__AD_GEO.ready() gave %s, expected known RS' % json.dumps(signal))
        results.append({'dir': entry['path'], 'identicalToDirect': entry['identical'], 'programs': {entry['path']: {'passed': not problems, 'problems': problems, 'signal': signal}}})
        if problems:
            failures.append('%s: %s' % (entry['path'], '; '.join(problems)))
        print('ok    ' if not problems else 'FAILED', entry['path'], '; '.join(problems) or 'country %s' % signal['country'])
    version = browser.version
    browser.close()

report = {'scope': 'Chromium %s, repository GPT/Prebid mock, TCF stub with all purposes granted, external requests aborted, virtual clock' % version,
          'compiledSha256': manifest['compiledSha256'], 'programs': sum(len(row['programs']) for row in results), 'seconds': round(time.time() - started, 1),
          'abortedRequests': sorted(set(outbound)), 'results': results, 'failures': failures, 'passed': not failures}
(output / 'browser-results.json').write_text(json.dumps(report, indent=1) + '\n')
print(json.dumps({'programs': report['programs'], 'failures': len(failures), 'seconds': report['seconds']}))
if not manifest['served']:
    failures.insert(0, 'the manifest has no served script')
if not manifest['passed']:
    failures.insert(0, 'the Worker generation parity check failed: %d checks' % len(manifest['failures']))
assert not failures, '%d programs failed:\n%s' % (len(failures), '\n'.join(failures))
